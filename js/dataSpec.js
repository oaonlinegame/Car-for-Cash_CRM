// โมดูลกำหนดโครงสร้างข้อมูลมาตรฐาน (Data Schema Definition)
// ทำหน้าที่เป็น Model Factory เพื่อควบคุมโครงสร้าง Object ทั่วทั้งระบบ
// ประกันความถูกต้องของข้อมูลก่อนการประมวลผลหรือบันทึกลงฐานข้อมูล
// --------------------------------------------------------

(function (global) {
  "use strict";

  const DataSpec = {
    // ========================================================================
    // 1. LEAD MODEL (โครงสร้างข้อมูลหลักของลูกค้า)
    // ========================================================================
    // กำหนดโครงสร้างเริ่มต้นสำหรับข้อมูล Lead เพื่อใช้ในการสร้างรายการใหม่
    // และใช้เป็นต้นแบบในการรีเซ็ตฟอร์ม (Form Reset) ให้กลับสู่สถานะว่าง

    Lead: {
      /**
       * สร้าง Object ข้อมูล Lead เริ่มต้น (Default State)
       * @returns {Object} โครงสร้างข้อมูลลูกค้าที่พร้อมสำหรับการทำ Data Binding
       */
      createDefault() {
        return {
          // --- ระบบระบุตัวตน (Identity) ---
          id: null,

          // --- ข้อมูลบุคคล (Personal Info) ---
          firstName: "", // ชื่อจริงหรือชื่อบริษัท
          lastName: "", // นามสกุล
          ContactPerson: "", // ชื่อผู้ติดต่อ (เพิ่มให้ตรงกับ UI)
          nickName: "", // ชื่อเล่น
          birthDate: "", // วันเกิด
          idCard: "", // เลขประจำตัวประชาชน
          occupation: "", // อาชีพหลัก
          occupationDetail: "", // รายละเอียดงาน/สถานที่ทำงาน

          // --- ข้อมูลการติดต่อ (Contact Info) ---
          phones: "", // หมายเลขโทรศัพท์หลัก
          phone2: "", // หมายเลขโทรศัพท์สำรอง
          lineId: "", // ไอดีไลน์
          facebook: "", // เฟซบุ๊ก
          address: "", // ที่อยู่ปัจจุบัน

          // --- บุคคลอ้างอิง (Emergency Contact) ---
          refName: "", // ชื่อบุคคลอ้างอิง
          refPhone: "", // เบอร์โทรบุคคลอ้างอิง

          // --- แหล่งที่มาของข้อมูล (Marketing Source) ---
          source: "", // ช่องทางที่ได้รับข้อมูล
          sourceNote: "", // บันทึกแหล่งที่มา
          sourceSocialName: "", // ชื่อโปรไฟล์โซเชียล (FB/Line/Tiktok)
          sourceRefName: "", // ชื่อผู้แนะนำ
          sourceRefContact: "", // ข้อมูลติดต่อผู้แนะนำ
          sourceEventName: "", // ชื่อกิจกรรม/อีเวนต์
          sourceEventDate: "", // วันที่จัดกิจกรรม

          // --- สถานะและระบบจัดการ (System & Meta) ---
          isProspect: false, // สถานะลูกค้าใหม่
          prospectStage: "สนใจ", // ขั้นตอนการขาย
          createDate: null, // วันที่เพิ่มข้อมูล
          note: "", // บันทึกทั่วไป
          rating: 0, // คะแนน (0-5 ดาว)

          // --- การเชื่อมโยงข้อมูล (Data Relations) ---
          contracts: [], // รายการสัญญา
          assets: [global.DataSpec?.Asset?.createDefault() || {}], // รายการหลักทรัพย์เริ่มต้น

          // --- ระบบค้นหาภายใน ---
          _searchIndex: "",
        };
      },
    },

    // ========================================================================
    // 2. CONTRACT MODEL (โครงสร้างข้อมูลสัญญา)
    // ========================================================================
    // กำหนดรูปแบบข้อมูลสำหรับการทำธุรกรรมทางการเงินและนิติกรรม

    Contract: {
      /**
       * สร้าง Object ข้อมูล Contract เริ่มต้น
       * @returns {Object} โครงสร้างข้อมูลสัญญาพร้อมวันที่ปัจจุบันตามมาตรฐานระบบ
       */
      createDefault() {
        return {
          // --- ข้อมูลอ้างอิงนิติกรรม (Contract Identity) ---
          contractId: "", // รหัสอ้างอิงภายในระบบ (Generated ID)
          contractNo: "", // เลขที่สัญญาตามเอกสารจริง
          signDate: new Date().toISOString().substr(0, 10), // วันที่เริ่มสัญญา (ค่าเริ่มต้นคือวันที่ปัจจุบัน)

          // --- ข้อมูลทางการเงิน (Finance Data) ---
          financeAmount: 0, // ยอดเงินต้นหรือยอดจัดสินเชื่อ
          interestRate: 0, // อัตราดอกเบี้ยร้อยละต่อปี
          terms: 0, // ระยะเวลาการผ่อนชำระ (จำนวนงวด)
          installment: 0, // ยอดชำระต่องวดที่คำนวณแล้ว

          // --- สถานะการดำเนินงาน (Operational Status) ---
          status: "Draft", // สถานะเริ่มต้นของสัญญาเมื่อถูกสร้างขึ้นครั้งแรก

          // --- ความสัมพันธ์ทางข้อมูล (Relational Keys) ---
          leadId: null, // Key อ้างอิงไปยังข้อมูลเจ้าของสัญญา (Lead)
          guarantorId: null, // Key อ้างอิงไปยังข้อมูลผู้ค้ำประกัน (ถ้ามี)

          // --- รายการหลักทรัพย์ค้ำประกัน (Collateral Assets) ---
          // กำหนดรายการทรัพย์สินที่ใช้ค้ำประกันภายใต้สัญญาฉบับนี้
          // เริ่มต้นด้วยโครงสร้าง Asset เปล่า 1 รายการเพื่อลดขั้นตอนการกดเพิ่มใน UI
          assets: [DataSpec.Asset.createDefault()],
        };
      },
    },

    // ========================================================================
    // 3. ASSET MODEL (โครงสร้างข้อมูลหลักทรัพย์/ทรัพย์สิน)
    // ========================================================================
    // กำหนดโครงสร้างข้อมูลทรัพย์สินประเภทต่างๆ ที่รองรับในระบบ
    // โดยรวมฟิลด์เฉพาะทาง (Specific Fields) ไว้ใน Object เดียวเพื่อความยืดหยุ่นในการใช้งาน

    Asset: {
      /**
       * สร้าง Object ข้อมูล Asset เริ่มต้น
       * @returns {Object} โครงสร้างข้อมูลหลักทรัพย์ที่มีคุณสมบัติครบทุกประเภททรัพย์สิน
       */
      createDefault() {
        return {
          // --- ข้อมูลจำแนกประเภท (Classification) ---
          // กำหนดค่าเริ่มต้นเป็น "รถยนต์" เนื่องจากเป็นประเภทที่มีการใช้งานบ่อยที่สุด
          type: "รถยนต์",
          subType: "", // ประเภทย่อยเพื่อการจัดหมวดหมู่ที่ละเอียดขึ้น

          // --- ฟิลด์ข้อมูลทั่วไป (Common Fields) ---
          details: "", // รายละเอียดทางกายภาพทั่วไป
          value: "", // มูลค่าประเมินหรือทุนประกันของทรัพย์สิน
          note: "", // บันทึกพิเศษเกี่ยวกับสภาพหรือประวัติทรัพย์สิน

          // --- ข้อมูลเฉพาะสำหรับกลุ่มยานพาหนะ (Car Specific) ---
          brand: "", // ยี่ห้อผู้ผลิต
          model: "", // รุ่นของยานพาหนะ
          year: "", // ปีที่ผลิตหรือปีจดทะเบียน
          engineSize: "", // ขนาดความจุเครื่องยนต์ (CC)
          engineNo: "", // หมายเลขเครื่องยนต์ตามเล่มทะเบียน
          chassisNo: "", // หมายเลขตัวถังสำหรับการตรวจสอบประวัติ
          plSequence: "", // ลำดับในบัญชีรายการ (PL Sequence)

          // --- ข้อมูลเฉพาะสำหรับกลุ่มอสังหาริมทรัพย์ (Land Specific) ---
          deedNo: "", // หมายเลขโฉนดที่ดิน
          landSize: "", // ขนาดพื้นที่ (ระบุเป็น ไร่-งาน-วา)
          province: "", // จังหวัดที่ตั้งทรัพย์สิน
          district: "", // อำเภอ/เขต ที่ตั้งทรัพย์สิน

          // --- ข้อมูลเฉพาะสำหรับกลุ่มงานประกันภัย (Insurance Specific) ---
          coverage: "", // รายละเอียดความคุ้มครองตามกรมธรรม์
          premium: "", // ยอดเงินค่าเบี้ยประกัน
          expiryDate: "", // วันที่สิ้นสุดความคุ้มครอง

          // --- ข้อมูลเฉพาะสำหรับกลุ่มสิทธิสวัสดิการ (Pension Specific) ---
          pensionAmount: "", // ยอดเงินสวัสดิการหรือบำนาญที่ได้รับต่อเดือน
        };
      },
    },
  };

  // --------------------------------------------------------
  // การส่งออกโมดูลไปยังส่วนควบคุมหลัก (Global Export)
  // --------------------------------------------------------
  // กำหนดให้ DataSpec เป็น Global Object เพื่อให้ไฟล์ Logic อื่นๆ
  // สามารถเรียกใช้โครงสร้างข้อมูลมาตรฐานนี้ได้โดยตรง
  global.DataSpec = DataSpec;
})(window);
