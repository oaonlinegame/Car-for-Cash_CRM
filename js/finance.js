// finance.js
// --------------------------------------------------------
// 📘 โมดูลคำนวณสินเชื่อ (Finance Module)
// --------------------------------------------------------
// หน้าที่ของไฟล์นี้:
// - เก็บตัวแปรและฟังก์ชันเกี่ยวกับการคำนวณยอดสินเชื่อ
// - ไม่มีการบันทึกถาวร (ไม่ใช้ LocalStorage / Dexie)
// - ใช้เป็น Utility สำหรับคำนวณแบบต่าง ๆ
// --------------------------------------------------------

// --------------------------------------------------------
// ⭐ Finance: ตัวแปรหลัก (Reactive) สำหรับหน้าจอ UI
// --------------------------------------------------------
const Finance = {
  loan: Vue.ref(0), // ตัวแปรยอดสินเชื่อที่คำนวณได้
  interestRate: Vue.ref(0), // อัตราดอกเบี้ย (%)
  termMonths: Vue.ref(0), // จำนวนงวดทั้งหมด
  monthlyPay: Vue.ref(0), // ค่างวดที่ต้องชำระต่อเดือน
};

// --------------------------------------------------------
// ⭐ FinanceLogic: ฟังก์ชันคำนวณสินเชื่อทั้งหมด
// --------------------------------------------------------
const FinanceLogic = {
  // ----------------------------------------------------
  // 🧮 calculateLoan(balance)
  // ฟังก์ชันคำนวณยอดกู้จากวงเงิน
  // ----------------------------------------------------
  calculateLoan(balance) {
    // แปลง balance ให้เป็นเลข
    const num = Number(balance) || 0; // ถ้าไม่ใช่เลขให้เป็น 0
    Finance.loan.value = num * 0.7; // ตัวอย่าง: คิดยอดได้ 70% ของราคาทรัพย์สิน

    console.log("💰 คำนวณยอดกู้:", Finance.loan.value);
  },

  // ----------------------------------------------------
  // 🧮 calculateInstallment(amount, rate, months)
  // ฟังก์ชันคำนวณค่างวดต่อเดือนแบบดอกเบี้ยคงที่
  //-----------------------------------------------------
  calculateInstallment(amount, rate, months) {
    const P = Number(amount) || 0; // วงเงินกู้
    const R = (Number(rate) || 0) / 100; // อัตราดอกเบี้ย (% → ทศนิยม)
    const N = Number(months) || 0; // จำนวนงวด

    if (P <= 0 || N <= 0) {
      Finance.monthlyPay.value = 0; // ถ้าข้อมูลไม่ครบ ให้ผลเป็น 0
      return;
    }

    // สูตรค่างวดแบบดอกเบี้ยคงที่ (Flat Rate)
    const totalInterest = P * R * (N / 12); // ดอกเบี้ยตลอดสัญญา
    const totalPay = P + totalInterest; // ยอดที่ต้องชำระทั้งหมด
    const perMonth = totalPay / N; // ค่างวดต่อเดือน

    Finance.monthlyPay.value = perMonth.toFixed(2); // ตัดทศนิยม 2 ตำแหน่ง

    console.log("📆 คำนวณค่างวดต่อเดือน:", Finance.monthlyPay.value);
  },

  // ----------------------------------------------------
  // 🧮 reset()
  // ฟังก์ชันล้างค่าคำนวณทั้งหมด
  // ----------------------------------------------------
  reset() {
    Finance.loan.value = 0; // รีเซ็ตยอดกู้
    Finance.interestRate.value = 0; // รีเซ็ตดอกเบี้ย
    Finance.termMonths.value = 0; // รีเซ็ตจำนวนงวด
    Finance.monthlyPay.value = 0; // รีเซ็ตค่างวด

    console.log("🔄 รีเซ็ตค่าคำนวณสินเชื่อทั้งหมด");
  },
};

// --------------------------------------------------------
// 🌍 export ออกไปใช้งานจากไฟล์อื่น
// --------------------------------------------------------
window.Finance = Finance;
window.FinanceLogic = FinanceLogic;
