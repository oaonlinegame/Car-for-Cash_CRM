// car.js
// --------------------------------------------------------
// 📘 โมดูลจัดการข้อมูลรถยนต์ (CarApp)
// --------------------------------------------------------
// ✅ ปรับปรุงใหม่: ยุบรวม State และ Logic เป็นอ็อบเจกต์เดียว (CarApp)
// ✅ ตัด CarState ที่แยกต่างหากออก เพื่อลดความซ้ำซ้อน
// --------------------------------------------------------

const CarApp = {
  // ------------------------------------------------------
  // ⭐ Data: เก็บข้อมูลสถานะและฟอร์ม (Reactive)
  // ------------------------------------------------------
  data: Vue.reactive({
    // คอมเมนต์: รายการรถทั้งหมด (เตรียมไว้สำหรับอนาคต)
    items: [],

    // คอมเมนต์: ฟอร์มสำหรับกรอกข้อมูลรถ (รวมจาก CarState เดิม)
    form: {
      brand: "", // คอมเมนต์: ยี่ห้อรถ
      model: "", // คอมเมนต์: รุ่นรถ
      color: "", // คอมเมนต์: สีรถ
      plate: "", // คอมเมนต์: ทะเบียนรถ
      year: "", // คอมเมนต์: ปีรถ
    },
  }),

  // ------------------------------------------------------
  // ⭐ Logic: ฟังก์ชันจัดการข้อมูล (Methods)
  // ------------------------------------------------------

  // 💰 selectPrice(price)
  // ฟังก์ชันเมื่อผู้ใช้กดเลือกราคาจากตาราง (ใช้ใน index.html)
  // ------------------------------------------------------
  selectPrice(price) {
    // คอมเมนต์: แสดงราคาทีเลือกใน Console เพื่อตรวจสอบ
    console.log("💰 CarApp: เลือกราคา", price);

    // คอมเมนต์: เรียกใช้ระบบแจ้งเตือน (ถ้ามี)
    if (window.AppNotifications) {
      AppNotifications.show(`✅ เลือกราคา ${price} เรียบร้อย`); // คอมเมนต์: แจ้งเตือนผู้ใช้
    }

    // คอมเมนต์: สั่งปิด Modal เลือกราคา (ถ้ามี AppGui)
    if (window.AppGui) {
      AppGui.toggleMenu("isOpenModalCarPriceSelector", false); // คอมเมนต์: ปิด Modal
    }
  },

  // ➕ add()
  // ฟังก์ชันเพิ่มรถใหม่ (รวม Logic การเพิ่มรถไว้ที่นี่)
  // ------------------------------------------------------
  add() {
    // คอมเมนต์: ดึงค่าจาก form มาสร้าง Object ใหม่
    const newItem = { ...this.data.form };

    // คอมเมนต์: เพิ่มลงในรายการ items
    this.data.items.push(newItem);

    // คอมเมนต์: รีเซ็ตฟอร์มให้ว่าง
    Object.keys(this.data.form).forEach((key) => {
      this.data.form[key] = ""; // คอมเมนต์: ล้างค่าทีละฟิลด์
    });

    // คอมเมนต์: แจ้งเตือนและ Log
    if (window.AppNotifications)
      AppNotifications.show("🚗 เพิ่มข้อมูลรถเรียบร้อย");
    console.log("🚗 CarApp: เพิ่มรถใหม่สำเร็จ", newItem);
  },

  // 🗑️ remove(index)
  // ฟังก์ชันลบรถตามลำดับ Index
  // ------------------------------------------------------
  remove(index) {
    // คอมเมนต์: ตัดรายการออกจาก Array ตาม index
    this.data.items.splice(index, 1);

    // คอมเมนต์: แจ้งเตือน
    if (window.AppNotifications) AppNotifications.show("🗑️ ลบข้อมูลรถสำเร็จ");
    console.log("🗑️ CarApp: ลบรถลำดับที่", index);
  },
};

// --------------------------------------------------------
// 🌍 Export ออกสู่ Global (เพื่อให้ไฟล์อื่นเรียกใช้ได้)
// --------------------------------------------------------
window.CarApp = CarApp;
