// car.js
// --------------------------------------------------------
// 📘 โมดูลจัดการข้อมูลรถยนต์ (Car Module)
// --------------------------------------------------------
// หมายเหตุ:
// - ใช้เป็น Utility Layer สำหรับเก็บข้อมูลรถในหน้าจอ
// - ยังไม่บันทึกถาวรลง Dexie (จะเพิ่มในอนาคตได้ง่าย)
// - ไม่มี LocalStorage
// - คอมเมนต์ทุกบรรทัดตามกติกาโปรเจกต์
// --------------------------------------------------------

// --------------------------------------------------------
// ⭐ CarState: เก็บข้อมูลรถใน UI แบบ reactive
// --------------------------------------------------------
const CarState = Vue.reactive({
  // รายการรถทั้งหมดในระบบ (UI Layer)
  carItems: [], // ตอนนี้เป็น array ว่าง (ยังไม่เชื่อม Dexie)

  // แบบฟอร์มเพิ่มรถใหม่ (ตัวอย่างเบื้องต้น)
  form: {
    brand: "", // ยี่ห้อรถ เช่น Toyota
    model: "", // รุ่นรถ เช่น Camry
    color: "", // สีรถ
    plate: "", // ทะเบียนรถ
    year: "", // ปีรถ
  },
});

// --------------------------------------------------------
// ⭐ CarLogic: ฟังก์ชันจัดการข้อมูลรถใน UI
// --------------------------------------------------------
const CarLogic = {
  // ----------------------------------------------------
  // 🟢 addCar()
  // ฟังก์ชันเพิ่มรถใหม่เฉพาะใน UI Layer
  // ----------------------------------------------------
  addCar() {
    // สร้างข้อมูลรถใหม่จากฟอร์ม
    const item = {
      brand: CarState.form.brand || "", // ยี่ห้อ
      model: CarState.form.model || "", // รุ่น
      color: CarState.form.color || "", // สี
      plate: CarState.form.plate || "", // ทะเบียน
      year: CarState.form.year || "", // ปี
    };

    // เพิ่มเข้ารายการรถใน UI
    CarState.carItems.push(item);

    // ล้างฟอร์มหลังบันทึก
    Object.keys(CarState.form).forEach((k) => {
      CarState.form[k] = ""; // รีเซ็ตค่าแต่ละช่อง
    });

    // แจ้งเตือนผู้ใช้
    AppNotifications.show("🚗 เพิ่มข้อมูลรถเรียบร้อยแล้ว");

    // debug
    console.log("🚗 เพิ่มรถใหม่:", item);
  },

  // ----------------------------------------------------
  // 🗑️ removeCar(index)
  // ลบรายการรถใน UI ตามลำดับ index
  // ----------------------------------------------------
  removeCar(index) {
    CarState.carItems.splice(index, 1); // ลบรายการที่ระบุ
    AppNotifications.show("🗑️ ลบข้อมูลรถสำเร็จ");

    console.log("🗑️ ลบรถลำดับ:", index);
  },

  // ----------------------------------------------------
  // 🔄 resetForm()
  // ล้างค่าฟอร์มทั้งหมด
  // ----------------------------------------------------
  resetForm() {
    Object.keys(CarState.form).forEach((k) => {
      CarState.form[k] = ""; // ล้างทุกฟิลด์
    });

    console.log("🔄 รีเซ็ตฟอร์มรถแล้ว");
  },
};

// --------------------------------------------------------
// 🌍 export สู่ global ให้ไฟล์อื่นเรียกใช้ได้
// --------------------------------------------------------
window.CarState = CarState;
window.CarLogic = CarLogic;
