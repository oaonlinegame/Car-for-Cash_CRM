// 📘 โมดูลสร้างข้อมูลทดสอบจำนวนมากสำหรับระบบ Lead Manager
// --------------------------------------------------------
// 💡 วิธีใช้
// 1) วางไฟล์นี้ในโฟลเดอร์ /js/
// 2) เพิ่ม <script src="./js/testData.js"></script> ก่อน app.js
// 3) เรียกใช้ TestData.generate1000() เพื่อสร้างข้อมูลทดสอบ
// --------------------------------------------------------

const TestData = {
  // ----------------------------------------------------
  // ⭐ ตัวเลือกข้อมูลสุ่ม
  // ----------------------------------------------------
  firstNames: [
    "สมชาย",
    "สมหญิง",
    "อาทิตย์",
    "วรัญญา",
    "มานพ",
    "ชลธิชา",
    "เดชา",
    "ณัฐชา",
    "อธิป",
    "พรทิพย์",
  ],
  provinces: [
    "กรุงเทพ",
    "เชียงใหม่",
    "ขอนแก่น",
    "นครราชสีมา",
    "ชลบุรี",
    "ภูเก็ต",
  ],
  statuses: [
    "ลูกค้าใหม่",
    "ลูกค้าเช่าซื้อ",
    "ลูกค้าจำนำทะเบียน",
    "ติดตาม",
    "ไม่สนใจ",
  ],
  stages: ["สนใจ", "รอเสนอ", "รอเอกสาร", "ติดตาม", "ปิดการขาย"],

  // ----------------------------------------------------
  // ⭐ ฟังก์ชันสุ่มง่าย ๆ
  // ----------------------------------------------------
  rand(arr) {
    return arr[Math.floor(Math.random() * arr.length)]; // คืนค่าจาก array แบบสุ่ม
  },

  randomPhone() {
    return "09" + Math.floor(10000000 + Math.random() * 90000000); // คืนเบอร์โทรแบบสุ่ม
  },

  // ----------------------------------------------------
  // 🟦 generate1000(): สร้าง Lead จำนวน 1000 รายการ
  // ----------------------------------------------------
  async generate1000() {
    AppNotifications.show("⏳ กำลังสร้างข้อมูลทดสอบ 1,000 รายการ...");

    // ล้าง Lead เดิมก่อน (กันซ้ำ)
    await AppDexie.lead.clear();

    const bulk = []; // เก็บรายการทั้งหมดก่อนบันทึก

    // ------------------------------------------------
    // 🔄 วนสร้างข้อมูล 1000 รายการ
    // ------------------------------------------------
    for (let i = 1; i <= 10000; i++) {
      const item = {
        firstName: this.rand(this.firstNames) + " ทดสอบ" + i, // ชื่อ
        nickName: "ทดสอบ" + i, // ชื่อเล่นสุ่ม
        phones: this.randomPhone() + "," + this.randomPhone(), // เบอร์ 2 เบอร์
        status: this.rand(this.statuses), // สถานะ
        occupation: "พนักงานบริษัท", // อาชีพ
        address: "บ้านเลขที่ " + Math.floor(Math.random() * 200), // ที่อยู่
        province: this.rand(this.provinces), // จังหวัด
        postalCode: ("10" + Math.floor(Math.random() * 1900)).slice(0, 5), // ไปรษณีย์สุ่ม
        prospectStage: this.rand(this.stages), // ขั้นตอนขาย
        rating: Math.floor(1 + Math.random() * 5), // คะแนน 1–5
        note: "ลูกค้าทดสอบระบบ", // หมายเหตุ
        isProspect: Math.random() > 0.5, // ลูกค้าใหม่หรือไม่
        createDate: new Date(Date.now() - Math.random() * 1e10)
          .toISOString()
          .slice(0, 10), // วันที่สุ่ม
      };

      bulk.push(item); // เก็บไว้ก่อน
    }

    // ------------------------------------------------
    // 💾 บันทึกทั้งหมดลง Dexie
    // ------------------------------------------------
    for (const item of bulk) {
      await AppDexie.lead.add(item); // บันทึกทีละรายการ
    }

    // ------------------------------------------------
    // 🔄 โหลดกลับขึ้น UI
    // ------------------------------------------------
    await LeadApp.loadAll();

    // ------------------------------------------------
    // 🎉 แจ้งผล
    // ------------------------------------------------
    AppNotifications.show(`🎉 สร้างข้อมูลทดสอบสำเร็จแล้ว 1,000 รายการ!`);
    console.log("🎉 TestData → เพิ่มข้อมูลทดสอบแล้ว:", bulk.length, "รายการ");
  },
};

// --------------------------------------------------------
// 📌 export
// --------------------------------------------------------
window.TestData = TestData;
